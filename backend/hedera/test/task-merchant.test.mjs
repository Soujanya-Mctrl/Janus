import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import http from 'node:http';
import { once } from 'node:events';
import { test } from 'node:test';
import { createPublicClient, createWalletClient, custom, defineChain, keccak256, stringToHex } from 'viem';
import { privateKeyToAccount } from 'viem/accounts';
import ganache from '../../../contracts/node_modules/ganache/dist/node/core.js';
import { createTaskMerchant, taskMerchantHandler, accessMessage, requestHash } from '../lib/task-merchant.mjs';
import { buyTaskDataset } from '../lib/task-client.mjs';
import { encodeAuthorization } from '../../../shared/protocol.mjs';

test('local EVM paid HTTP request survives response loss, restart and worker replacement', async t => {
 const directory = await fs.mkdtemp(path.join(os.tmpdir(), 'janus-paid-'));
 const provider = ganache.provider({ logging: { quiet: true }, wallet: { deterministic: true }, chain: { chainId: 1337, hardfork: 'shanghai' } });
 t.after(async () => { await provider.disconnect(); await fs.rm(directory, { recursive: true, force: true }); });
 const chain = defineChain({ id: 1337, name: 'Local', nativeCurrency: { name: 'Ether', symbol: 'ETH', decimals: 18 }, rpcUrls: { default: { http: ['http://localhost'] } } });
 const transport = custom(provider), publicClient = createPublicClient({ chain, transport, cacheTime: 0, pollingInterval: 10 });
 const wallets = Object.values(provider.getInitialAccounts()).map(entry => createWalletClient({ account: privateKeyToAccount(entry.secretKey), chain, transport }));
 const artifact = name => fs.readFile(new URL(`../../../contracts/phase1/artifacts/${name}.json`, import.meta.url), 'utf8').then(JSON.parse);
 const tokenArtifact = await artifact('TestToken'), treasuryArtifact = await artifact('TaskTreasury');
 const receipt = async hash => { const result = await publicClient.waitForTransactionReceipt({ hash }); assert.equal(result.status, 'success'); return result; };
 const token = (await receipt(await wallets[0].deployContract({ abi: tokenArtifact.abi, bytecode: tokenArtifact.bytecode }))).contractAddress;
 const treasury = (await receipt(await wallets[0].deployContract({ abi: treasuryArtifact.abi, bytecode: treasuryArtifact.bytecode, args: [token] }))).contractAddress;
 const abi = treasuryArtifact.abi;
 const send = (wallet, functionName, args) => wallet.writeContract({ address: treasury, abi, functionName, args }).then(receipt);
 await receipt(await wallets[0].writeContract({ address: token, abi: tokenArtifact.abi, functionName: 'approve', args: [treasury, 1000n] }));
 await send(wallets[0], 'deposit', [1000n]);
 const taskId = keccak256(stringToHex('task-A')), operationId = keccak256(stringToHex('dataset'));
 await send(wallets[0], 'createTask', [taskId, wallets[1].account.address, wallets[3].account.address, 100n, 30n]);
 const other = keccak256(stringToHex('task-B'));
 await send(wallets[0], 'createTask', [other, wallets[2].account.address, wallets[3].account.address, 100n, 30n]);
 const descriptor = JSON.parse(await fs.readFile(new URL('../../../shared/treasury-interface.json', import.meta.url), 'utf8'));
 const manifest = { interfaceVersion: descriptor.interfaceVersion, abiHash: descriptor.abiHash, mode: 'local', chainId: 1337,
  treasury, token, owner: wallets[0].account.address, runtimeCodeHash: keccak256(await publicClient.getBytecode({ address: treasury })) };
 const request = { chainId: '1337', treasury, token, merchant: wallets[3].account.address, amount: '20', route: '/dataset', body: { dataset: 'one' } };
 const authorization = encodeAuthorization(taskId, operationId, '1');
 await send(wallets[1], 'reserve', [taskId, operationId, requestHash(request), 20n, 1n, 1n, 300n]);
 let fail = true;
 const make = (options = {}) => createTaskMerchant({ directory, publicClient, walletClient: wallets[3], manifest, price: '20', confirmations: 1,
  produce: async () => { if (fail) throw new Error('Injected post-payment loss'); return { dataset: 'original' }; }, ...options });
 let merchant = await make();
 const server = http.createServer((req, res) => taskMerchantHandler(merchant)(req, res));
 t.after(() => new Promise(resolve => { server.closeAllConnections(); server.close(resolve); }));
 server.listen(0, '127.0.0.1'); await once(server, 'listening');
 const post = async (route, input) => fetch(`http://127.0.0.1:${server.address().port}${route}`, { method: 'POST', body: JSON.stringify(input) });
 const principal = async wallet => { const expiresAt = String(Math.floor(Date.now() / 1000) + 120); return { address: wallet.account.address, expiresAt,
  signature: await wallet.signMessage({ message: accessMessage(authorization, request, expiresAt) }) }; };
 const quote = await (await post('/quote', { authorization, request })).json();
 assert.equal((await post('/purchase', { quote, authorization, request, principal: await principal(wallets[1]) })).status, 409);
 const read = (name, args = []) => publicClient.readContract({ address: treasury, abi, functionName: name, args });
 assert.equal(await read('totalSpent'), 20n);
 await send(wallets[0], 'assignWorker', [taskId, wallets[2].account.address]);
 fail = false; merchant = await make({ logPageSize: 1n });
 assert.equal((await post('/purchase', { quote, authorization, request, principal: await principal(wallets[1]) })).status, 409);
 const recovered = await post('/purchase', { quote, authorization, request, principal: await principal(wallets[2]) });
 assert.equal(recovered.status, 200); const original = await recovered.json(); assert.equal(original.result, '{"dataset":"original"}');
 assert.equal((await post('/purchase', { quote, authorization, request: { ...request, amount: '21' }, principal: await principal(wallets[2]) })).status, 409);
 const again = await post('/purchase', { quote, authorization, request, principal: await principal(wallets[2]) });
 assert.deepEqual(await again.json(), original); assert.equal(await read('totalSpent'), 20n);
 const awaitingFinality = await make({ confirmations: 1000000 });
 await assert.rejects(() => principal(wallets[2]).then(principal => awaitingFinality.purchase({ authorization, request, principal })), /reconciliation/);
 await assert.rejects(() => make({ confirmations: 0 }), /Invalid settlement policy/);
 assert.equal(await publicClient.readContract({ address: token, abi: tokenArtifact.abi, functionName: 'balanceOf', args: [wallets[3].account.address] }), 20n);
 // Lost local state is reconciled from the contract and original Paid log, never charged again.
 for (const name of await fs.readdir(directory)) await fs.unlink(path.join(directory, name));
 merchant = await make({ logPageSize: 1n });
 assert.equal((await post('/purchase', { quote, authorization, request, principal: await principal(wallets[2]) })).status, 409);
 assert.equal(await read('totalSpent'), 20n);
 await assert.rejects(() => publicClient.simulateContract({ account: wallets[1].account, address: treasury, abi, functionName: 'reserve', args: [taskId, keccak256(stringToHex('stale')), requestHash(request), 1n, 1n, 1n, 300n] }));
 await assert.rejects(() => principal(wallets[2]).then(principal => merchant.purchase({ authorization, request, principal })), /owner decision/);
 assert.equal((await read('tasks', [other]))[1], 100n);
 const sdkArgs = { publicClient, walletClient: wallets[2], endpoint: `http://127.0.0.1:${server.address().port}`, taskId: other, stepId: 'verified-dataset', request, manifest };
 const sdkResult = await buyTaskDataset(sdkArgs);
 assert.equal(sdkResult.status, 'ready');
 assert.deepEqual(await buyTaskDataset(sdkArgs), sdkResult);
 assert.equal(await read('totalSpent'), 40n);
 assert.equal((await read('tasks', [other]))[1], 80n);
});
